export type WebCopy = (typeof strings)["ar"];

export function webCopy(locale: Locale): WebCopy {
  return strings[locale];
}

export const dirFor = (locale: Locale) => (locale === "ar" ? "rtl" : "ltr");

export function formatMoney(amount: number, currency: "AED" | "SAR", locale: Locale): string {
  return new Intl.NumberFormat(locale === "ar" ? "ar-AE" : "en-AE", { style: "currency", currency, maximumFractionDigits: 2 }).format(amount);
}
